#!/usr/bin/env python3
"""Generate the Black-Scholes reference values the tests check, or check them.

    uv run --group scripts tools/black_scholes_sympy_value_check.py          # write
    uv run --group scripts tools/black_scholes_sympy_value_check.py --check  # compare

sympy differentiates the call price of tests/fixtures/mc_sim/black_scholes.hpp
symbolically, and mpmath evaluates the price and its first derivatives at the
inputs below in 50-digit arithmetic. Each value is written as the double
nearest the exact one, to tests/fixtures/mc_sim/black_scholes_reference.hpp,
which tests/common/black_scholes_demo.cpp checks the engine against.

--check regenerates the header and fails unless the committed one matches;
pre-commit runs it.
"""

import sys
from pathlib import Path

import mpmath
from sympy import Symbol, erfc, lambdify, log, sqrt

mpmath.mp.dps = 50

HEADER = (
    Path(__file__).resolve().parent.parent
    / "tests/fixtures/mc_sim/black_scholes_reference.hpp"
)

# The inputs, as doubles; the values are exact for these doubles.
INPUTS = {"S": 104.25, "K": 98.5, "v": 0.22, "T": 1.2}


def call_price(S, K, v, T):
    def cdf(x):
        return erfc(-x / sqrt(2)) / 2

    totalvol = v * sqrt(T)
    d1 = log(S / K) / totalvol + totalvol / 2
    d2 = d1 - totalvol
    return S * cdf(d1) - K * cdf(d2)


def header():
    symbols = [Symbol(name) for name in INPUTS]
    price = call_price(*symbols)
    args = [mpmath.mpf(x) for x in INPUTS.values()]

    def value(expr):
        return repr(float(lambdify(symbols, expr, modules="mpmath")(*args)))

    lines = [
        f"// Generated by tools/{Path(__file__).name}; don't edit it by hand.",
        "// The Black-Scholes call price and its first derivatives at the inputs",
        "// below, exact for those doubles and rounded to the nearest double.",
        "",
        "#ifndef BLACK_SCHOLES_REFERENCE_HPP_INCLUDED",
        "#define BLACK_SCHOLES_REFERENCE_HPP_INCLUDED",
        "",
        "namespace black_scholes_reference {",
        "",
    ]
    lines += [f"inline constexpr double {k} = {v!r};" for k, v in INPUTS.items()]
    lines += ["", f"inline constexpr double price = {value(price)};"]
    lines += [
        f"inline constexpr double d_d{s} = {value(price.diff(s))};" for s in symbols
    ]
    lines += [
        "",
        "} // namespace black_scholes_reference",
        "",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def main():
    generated = header()
    if "--check" not in sys.argv[1:]:
        HEADER.write_text(generated)
        return 0
    if not HEADER.exists() or HEADER.read_text() != generated:
        print(
            f"{HEADER.name} differs from what {Path(__file__).name} generates. "
            "Run it without --check to rewrite it.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
